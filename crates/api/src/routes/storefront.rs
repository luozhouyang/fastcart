/// Public prefix used for theme client assets.
pub(crate) const THEME_ASSETS_BASE_URL: &str = "/api/v1/store/theme-assets";

/// Renders unmatched storefront requests through the configured runtime.
pub async fn render(State(context): State<Arc<AppContext>>, request: Request) -> Response {
    let path = request.uri().path();
    if is_reserved_path(path) {
        return ApiError::not_found("route").into_response();
    }
    let Some(host) = request
        .headers()
        .get(HOST)
        .and_then(|value| value.to_str().ok())
        .map(str::to_owned)
    else {
        return ApiError::new(AppError::validation("missing Host header")).into_response();
    };
    let store = match context.resolver.resolve_active(&host).await {
        Ok(store) => store,
        Err(_) => return ApiError::not_found("store").into_response(),
    };
    let database = match context.databases.database(&store.id).await {
        Ok(database) => database,
        Err(error) => return ApiError::new(AppError::from(error)).into_response(),
    };
    let content = ContentService::new(database.clone());
    if let Ok(redirect) = content.get_redirect_by_path(path).await {
        let status = StatusCode::from_u16(u16::try_from(redirect.status_code).unwrap_or(308))
            .unwrap_or(StatusCode::PERMANENT_REDIRECT);
        // Only site-relative destinations are honoured. Allowing absolute URLs
        // would turn merchant-configured redirects into an open redirect on a
        // trusted storefront domain.
        if let Some(location) = redirect_location(&redirect.to_path) {
            let mut response = status.into_response();
            response
                .headers_mut()
                .insert(axum::http::header::LOCATION, location);
            return response;
        }
        tracing::warn!(
            path = %path,
            to = %redirect.to_path,
            "ignoring redirect to a non-relative destination"
        );
    }
    // Discovery files are generated by the host, so they work even when SSR
    // rendering is disabled for this deployment.
    let scheme = public_scheme(request.headers());
    if path == "/robots.txt" {
        return robots_response(scheme, &host);
    }
    if path == "/sitemap.xml" {
        return sitemap_response(&content, &database, scheme, &host).await;
    }
    let Some(runtime) = context.storefront_runtime.clone() else {
        return ApiError::not_found("storefront route").into_response();
    };
    let currency = match CurrencyCode::new(store.currency_code.clone()) {
        Ok(currency) => currency,
        Err(error) => return ApiError::new(AppError::from(error)).into_response(),
    };
    let theme = match ThemeService::new(database.clone()).active().await {
        Ok(Some(theme)) => theme,
        Ok(None) => return ApiError::not_found("active theme").into_response(),
        Err(error) => return ApiError::new(error).into_response(),
    };
    let editor = resolve_active_editor(&context, &store.id, &theme).await;
    let mut page = load_storefront_page(&content, path).await;
    let mut route_context: Option<serde_json::Value> = None;
    if page.is_none()
        && let Some(route) = match_theme_route(&theme.manifest.routes, path)
        && let Ok(template) = content.get_published_page_by_type(&route.kind).await
    {
        let resolution = DataResolutionContext {
            currency: currency.clone(),
            sales_channel_id: None,
            customer_group_id: None,
            mode: DataMode::Production,
            now: now_timestamp(),
        };
        match context
            .storefront_data
            .resolve_route(&database, &route.kind, &route.handle, &resolution)
            .await
        {
            Ok(Some(resource)) => {
                route_context = Some(json!({
                    "kind": route.kind,
                    "handle": route.handle,
                    "resource": resource,
                }));
                page = Some(template);
            }
            Ok(None) => {}
            Err(error) => {
                tracing::warn!(
                    kind = %route.kind,
                    handle = %route.handle,
                    error = %error,
                    "could not resolve theme route resource"
                );
            }
        }
    }
    let compiled = match page {
        Some(page) => {
            let page_key = format!(
                "{}:{}:{}:{}",
                store.id.as_str(),
                page.id.as_str(),
                page.revision,
                editor.key
            );
            match context.storefront_page_cache.get(&page_key).await {
                Some(compiled) => Some(compiled),
                None => match compile_page(&page, editor.manifest.as_deref()) {
                    Ok(compiled) => {
                        let compiled = Arc::new(compiled);
                        context
                            .storefront_page_cache
                            .insert(page_key, compiled.clone())
                            .await;
                        Some(compiled)
                    }
                    Err(error) => {
                        tracing::warn!(
                            page_id = %page.id,
                            error = %error,
                            "stored page body is invalid"
                        );
                        None
                    }
                },
            }
        }
        None => None,
    };
    let mut data = BTreeMap::new();
    let mut context_entry = build_context_data(
        &context,
        &database,
        request.headers(),
        &store,
        &host,
        &currency,
        &theme,
        DataMode::Production,
    )
    .await;
    if let Some(route) = route_context {
        context_entry["route"] = route;
    }
    data.insert(
        fastcart_storefront::page::RESERVED_CONTEXT_KEY.to_owned(),
        context_entry,
    );
    if let Some(compiled) = compiled.as_ref()
        && !compiled.bindings.is_empty()
    {
        let resolution = DataResolutionContext {
            currency: currency.clone(),
            sales_channel_id: None,
            customer_group_id: None,
            mode: DataMode::Production,
            now: now_timestamp(),
        };
        match context
            .storefront_data
            .resolve(&database, &compiled.bindings, &resolution)
            .await
        {
            Ok(bag) => data.extend(bag),
            Err(error) => {
                context.metrics.record_storefront_data_failure();
                tracing::warn!(error = %error, "storefront data resolution failed");
            }
        }
    }
    let data = Some(serde_json::to_value(data).unwrap_or(serde_json::Value::Null));
    let page_context = compiled.as_ref().map(|compiled| compiled.page.clone());

    let request_id = request
        .extensions()
        .get::<RequestId>()
        .map(|id| id.0.clone())
        .unwrap_or_default();
    let method = request.method().as_str().to_owned();
    let url = request
        .uri()
        .path_and_query()
        .map_or_else(|| path.to_owned(), |value| value.as_str().to_owned());
    let headers = request
        .headers()
        .iter()
        .filter(|(name, _)| !is_hop_by_hop(name.as_str()) && name.as_str() != HOST)
        .filter_map(|(name, value)| {
            value
                .to_str()
                .ok()
                .map(|value| (name.as_str().to_owned(), value.to_owned()))
        })
        .collect();
    let (_, body) = request.into_parts();
    let body = match body.collect().await {
        Ok(body) => body.to_bytes(),
        Err(error) => {
            return ApiError::new(AppError::validation(format!(
                "could not read request body: {error}"
            )))
            .into_response();
        }
    };
    let capabilities = capability_grants(&context, &store.id, &database, &theme).await;
    let runtime_request = RuntimeRequest {
        request_id: request_id.clone(),
        store: StoreContext {
            store_id: store.id.clone(),
            domain: host,
            locale: store.locale.clone(),
            currency,
            timezone: store.timezone.clone(),
        },
        method,
        url,
        headers,
        body: (!body.is_empty()).then_some(body),
        theme: Some(RuntimeTheme {
            id: theme.manifest.id.clone(),
            version: theme.manifest.version.clone(),
            runtime: theme.manifest.runtime.clone(),
            bundle_path: theme.bundle_path.clone(),
            entry: theme.manifest.entry.clone(),
            settings: theme.settings.clone(),
            assets_manifest: theme.assets_manifest.clone(),
            assets_base_url: Some(THEME_ASSETS_BASE_URL.to_owned()),
        }),
        page: page_context,
        data,
        capabilities,
        mode: RuntimeMode::Production,
        timeout_ms: context.config.storefront_timeout_ms.max(1),
        streaming: context.config.storefront_streaming_enabled,
        stream_timeout_ms: context.config.storefront_stream_timeout_ms.max(1),
    };

    match runtime.render(runtime_request).await {
        Ok(response) => {
            runtime_response(response, context.config.storefront_stream_timeout_ms.max(1))
        }
        Err(RuntimeError::Timeout(timeout_ms)) => runtime_error(
            StatusCode::GATEWAY_TIMEOUT,
            "RUNTIME_TIMEOUT",
            &format!("storefront rendering timed out after {timeout_ms} ms"),
            &request_id,
        ),
        Err(RuntimeError::WorkerUnavailable(message)) => {
            tracing::warn!(error = %message, "storefront runtime unavailable");
            let mut response = runtime_error(
                StatusCode::SERVICE_UNAVAILABLE,
                "RUNTIME_UNAVAILABLE",
                "storefront rendering is temporarily unavailable",
                &request_id,
            );
            response.headers_mut().insert(
                axum::http::header::RETRY_AFTER,
                HeaderValue::from_static("5"),
            );
            response
        }
        Err(error) => {
            tracing::warn!(error = %error, "storefront runtime failed");
            runtime_error(
                StatusCode::BAD_GATEWAY,
                "RUNTIME_ERROR",
                "storefront rendering failed",
                &request_id,
            )
        }
    }
}

async fn load_storefront_page(content: &ContentService, path: &str) -> Option<Page> {
    let handle = path.trim_matches('/');
    // Storefront paths are flat: nested paths have no page handle and are
    // treated as an ordinary miss rather than being scanned for a match.
    let result = if handle.is_empty() {
        content.get_home_page().await
    } else {
        content.get_published_page_by_handle(handle).await.map(Some)
    };
    match result {
        Ok(Some(page)) if is_published_page(&page) => Some(page),
        Ok(_) => None,
        Err(error) if error.is_not_found() => None,
        Err(error) => {
            tracing::warn!(error = %error, "storefront page lookup failed");
            None
        }
    }
}

/// A dynamic theme route matched from the active manifest.
pub(crate) struct MatchedRoute {
    pub(crate) kind: String,
    pub(crate) handle: String,
}

/// Matches a request path against the theme's declared dynamic routes.
///
/// A route pattern contains exactly one `{handle}` placeholder. The most
/// specific static prefix wins when patterns overlap.
pub(crate) fn match_theme_route(
    routes: &std::collections::BTreeMap<String, String>,
    path: &str,
) -> Option<MatchedRoute> {
    let mut best: Option<(usize, MatchedRoute)> = None;
    for (kind, pattern) in routes {
        let Some((prefix, suffix)) = pattern.split_once("{handle}") else {
            continue;
        };
        let Some(rest) = path.strip_prefix(prefix) else {
            continue;
        };
        let Some(handle) = rest.strip_suffix(suffix) else {
            continue;
        };
        if handle.is_empty()
            || handle.contains('/')
            || validate_handle(handle, "route handle").is_err()
        {
            continue;
        }
        let specificity = prefix.len();
        if best
            .as_ref()
            .is_none_or(|(current, _)| specificity > *current)
        {
            best = Some((
                specificity,
                MatchedRoute {
                    kind: kind.clone(),
                    handle: handle.to_owned(),
                },
            ));
        }
    }
    best.map(|(_, route)| route)
}

/// Uses the proxy-declared scheme when present, otherwise HTTPS.
fn public_scheme(headers: &HeaderMap) -> &'static str {
    let forwarded = headers
        .get("x-forwarded-proto")
        .and_then(|value| value.to_str().ok())
        .and_then(|value| value.split(',').next())
        .map(str::trim);
    if forwarded == Some("http") {
        "http"
    } else {
        "https"
    }
}

/// Serves a default `robots.txt` that points crawlers at the store sitemap.
fn robots_response(scheme: &str, host: &str) -> Response {
    let body = format!("User-agent: *\nAllow: /\nSitemap: {scheme}://{host}/sitemap.xml\n");
    text_response(body, "text/plain; charset=utf-8")
}

/// Builds a sitemap for published content, products and collections.
///
/// Content pages always appear. Product and collection URLs are included only
/// when the active theme declares the matching route and a published template
/// page exists, so the sitemap never advertises URLs that render a 404.
async fn sitemap_response(
    content: &ContentService,
    database: &fastcart_infrastructure::StoreDatabase,
    scheme: &str,
    host: &str,
) -> Response {
    // Sitemaps are capped at 50,000 URLs per file; batches keep memory bounded
    // while every published record below the cap is included.
    const MAX_SITEMAP_URLS: i64 = 50_000;
    let mut xml = String::from(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n",
    );
    let mut seen = 0_i64;
    let mut offset = 0_i64;
    loop {
        let pagination = match fastcart_kernel::Pagination::new(
            Some(fastcart_kernel::Pagination::MAX_LIMIT),
            Some(offset),
        ) {
            Ok(pagination) => pagination,
            Err(error) => return ApiError::new(error).into_response(),
        };
        let pages = match content.list_published_routes(pagination).await {
            Ok(pages) => pages,
            Err(error) => return ApiError::new(error).into_response(),
        };
        let batch_len = pages.data.len();
        for page in pages.data {
            let loc = if page.page_type == "home" || page.handle == "home" {
                format!("{scheme}://{host}/")
            } else {
                format!("{scheme}://{host}/{}", xml_escape(&page.handle))
            };
            xml.push_str(&format!(
                "  <url><loc>{loc}</loc><lastmod>{}</lastmod></url>\n",
                xml_escape(&page.lastmod)
            ));
            seen += 1;
        }
        offset = offset.saturating_add(pagination.limit);
        if batch_len < usize::try_from(pagination.limit).unwrap_or(usize::MAX)
            || seen >= MAX_SITEMAP_URLS
        {
            break;
        }
    }

    let routes = ThemeService::new(database.clone())
        .active()
        .await
        .ok()
        .flatten()
        .map(|theme| theme.manifest.routes)
        .unwrap_or_default();
    'kinds: for (kind, pattern) in &routes {
        if seen >= MAX_SITEMAP_URLS || !pattern.contains("{handle}") {
            break;
        }
        // A route without a published template cannot serve traffic.
        if content.get_published_page_by_type(kind).await.is_err() {
            continue;
        }
        let mut offset = 0_i64;
        loop {
            let pagination = match fastcart_kernel::Pagination::new(
                Some(fastcart_kernel::Pagination::MAX_LIMIT),
                Some(offset),
            ) {
                Ok(pagination) => pagination,
                Err(error) => return ApiError::new(error).into_response(),
            };
            let catalog = fastcart_module_catalog::CatalogService::new(database.clone());
            let entries = match kind.as_str() {
                "product" => catalog.list_published_product_entries(pagination).await,
                "collection" => catalog.list_published_collection_entries(pagination).await,
                _ => break,
            };
            let entries = match entries {
                Ok(entries) => entries,
                Err(error) => return ApiError::new(error).into_response(),
            };
            let batch_len = entries.data.len();
            for entry in entries.data {
                let path = pattern.replace("{handle}", &xml_escape(&entry.handle));
                xml.push_str(&format!(
                    "  <url><loc>{scheme}://{host}{path}</loc><lastmod>{}</lastmod></url>\n",
                    xml_escape(&entry.lastmod)
                ));
                seen += 1;
                if seen >= MAX_SITEMAP_URLS {
                    break 'kinds;
                }
            }
            offset = offset.saturating_add(pagination.limit);
            if batch_len < usize::try_from(pagination.limit).unwrap_or(usize::MAX) {
                break;
            }
        }
    }

    xml.push_str("</urlset>\n");
    text_response(xml, "application/xml; charset=utf-8")
}

/// Returns a `Location` value only for safe, site-relative redirect targets.
///
/// Absolute URLs, scheme-relative URLs (`//host`), backslashes and control
/// characters are rejected so stored redirects cannot be abused for open
/// redirects on the merchant's domain.
fn redirect_location(to_path: &str) -> Option<HeaderValue> {
    let trimmed = to_path.trim();
    if !trimmed.starts_with('/')
        || trimmed.starts_with("//")
        || trimmed.contains('\\')
        || trimmed.bytes().any(|byte| byte.is_ascii_control())
    {
        return None;
    }
    HeaderValue::from_str(trimmed).ok()
}

fn text_response(body: String, content_type: &'static str) -> Response {
    Response::builder()
        .status(StatusCode::OK)
        .header(axum::http::header::CONTENT_TYPE, content_type)
        .header(axum::http::header::CACHE_CONTROL, "public, max-age=300")
        .header(
            axum::http::header::HeaderName::from_static("x-content-type-options"),
            "nosniff",
        )
        .body(Body::from(body))
        .unwrap_or_else(|_| StatusCode::INTERNAL_SERVER_ERROR.into_response())
}

fn xml_escape(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

/// A parsed active theme editor manifest and the cache key it was stored under.
///
/// The manifest is `None` when the stored value is absent or invalid, so an
/// invalid manifest is not re-parsed on every render.
pub(crate) struct ActiveEditor {
    /// Cache key derived from the store, theme identifier and revision.
    pub(crate) key: String,
    /// Parsed editor manifest, when the theme provides a valid one.
    pub(crate) manifest: Option<Arc<ThemeEditorManifest>>,
}

/// Loads and caches the active theme's editor manifest.
pub(crate) async fn resolve_active_editor(
    context: &AppContext,
    store_id: &StoreId,
    theme: &fastcart_module_theme::Theme,
) -> ActiveEditor {
    // The internal theme record id is unique per registration; `manifest.id`
    // can stay the same across re-registrations while the stored manifest
    // changes, so it must not be the cache identity.
    let key = format!(
        "{}:{}:{}",
        store_id.as_str(),
        theme.id.as_str(),
        theme.updated_at
    );
    let manifest = context
        .storefront_editor_cache
        .get_with(key.clone(), async {
            theme.editor_manifest.as_ref().and_then(|value| {
                match ThemeEditorManifest::parse(value) {
                    Ok(manifest) => Some(Arc::new(manifest)),
                    Err(error) => {
                        tracing::warn!(error = %error, "stored theme editor manifest is invalid");
                        None
                    }
                }
            })
        })
        .await;
    ActiveEditor { key, manifest }
}

/// Builds capability grants declared by the theme and bound by an operator.
pub(crate) async fn capability_grants(
    context: &AppContext,
    store_id: &StoreId,
    db: &StoreDatabase,
    theme: &fastcart_module_theme::Theme,
) -> BTreeMap<String, CapabilityGrant> {
    let Some(requirements) = theme.manifest.requires.as_ref() else {
        return BTreeMap::new();
    };
    let bindings = match ThemeService::new(db.clone())
        .list_capability_bindings(&theme.id)
        .await
    {
        Ok(bindings) => bindings,
        Err(error) => {
            tracing::warn!(error = %error, "could not load theme capability bindings");
            return BTreeMap::new();
        }
    };
    let mut grants = BTreeMap::new();
    for binding in bindings.into_iter().filter(|binding| binding.is_active) {
        let Some(requirement) = requirements
            .capabilities
            .iter()
            .find(|capability| capability.id == binding.capability_id)
        else {
            continue;
        };
        let token = capability_token(
            context.config.capability_secret.as_deref(),
            store_id,
            &theme.id,
            &binding.capability_id,
        );
        grants.insert(
            binding.capability_id,
            CapabilityGrant {
                version: requirement.version,
                endpoint: binding.endpoint,
                token,
                config: binding.config,
            },
        );
    }
    for requirement in &requirements.capabilities {
        if !requirement.optional && !grants.contains_key(&requirement.id) {
            tracing::warn!(
                theme_id = %theme.id,
                capability = %requirement.id,
                "required theme capability has no active binding"
            );
        }
    }
    grants
}

/// Mints a capability token for one request.
///
/// When `FASTCART_CAPABILITY_SECRET` is configured the token is a signed
/// payload (`store`, `theme`, `capability`, `exp`), so a capability endpoint
/// sharing the secret can verify it statelessly. Without a secret the token is
/// an opaque random identifier that only a stateful endpoint can recognise.
fn capability_token(
    secret: Option<&str>,
    store_id: &StoreId,
    theme_id: &fastcart_kernel::ThemeId,
    capability_id: &str,
) -> String {
    let Some(secret) = secret else {
        return uuid::Uuid::now_v7().simple().to_string();
    };
    let payload = json!({
        "store": store_id.as_str(),
        "theme": theme_id.as_str(),
        "capability": capability_id,
        "exp": now_timestamp().saturating_add(300),
    });
    let bytes = match serde_json::to_vec(&payload) {
        Ok(bytes) => bytes,
        Err(_) => return uuid::Uuid::now_v7().simple().to_string(),
    };
    let Ok(mut mac) = Hmac::<Sha256>::new_from_slice(secret.as_bytes()) else {
        return uuid::Uuid::now_v7().simple().to_string();
    };
    mac.update(&bytes);
    format!(
        "{}.{}",
        URL_SAFE_NO_PAD.encode(&bytes),
        URL_SAFE_NO_PAD.encode(mac.finalize().into_bytes())
    )
}

/// Parses and validates a page, then extracts its bindings in the same pass.
pub(crate) fn compile_page(
    page: &Page,
    editor: Option<&ThemeEditorManifest>,
) -> Result<CompiledPage, StorefrontError> {
    let body = PageBody::parse(&page.body)?;
    let bindings = match editor {
        Some(editor) => {
            body.validate_with_editor(editor)?;
            body.collect_bindings_after_validation(editor)?
        }
        None => Vec::new(),
    };
    Ok(CompiledPage {
        page: PageContext {
            id: page.id.as_str().to_owned(),
            handle: page.handle.clone(),
            status: page.status.as_str().to_owned(),
            page_type: page.page_type.clone(),
            title: page.title.clone(),
            seo: page.seo.clone(),
            body: serde_json::to_value(&body).unwrap_or(serde_json::Value::Null),
        },
        bindings,
    })
}

/// Builds the reserved `context` entry injected into every data bag.
///
/// The authenticated customer and their active cart are resolved from
/// store-scoped cookies. Lookup failures degrade to anonymous/null context
/// rather than failing the render: a theme must always receive a stable shape.
#[allow(clippy::too_many_arguments)]
pub(crate) async fn build_context_data(
    context: &AppContext,
    db: &StoreDatabase,
    headers: &HeaderMap,
    store: &fastcart_platform::Store,
    host: &str,
    currency: &CurrencyCode,
    theme: &fastcart_module_theme::Theme,
    mode: DataMode,
) -> serde_json::Value {
    let cookies = parse_cookies(headers);
    let customer = match cookies.get(CUSTOMER_SESSION_COOKIE) {
        Some(token) => resolve_context_customer(context, db, store.id.as_str(), token).await,
        None => None,
    };
    let cart = resolve_context_cart(
        context,
        db,
        store.id.as_str(),
        cookies.get(CART_ID_COOKIE).map(String::as_str),
        customer.as_deref(),
    )
    .await;
    let customer = customer.map(|customer| {
        json!({
            "id": customer.id.as_str(),
            "email": customer.email.clone(),
            "first_name": customer.first_name.clone(),
            "last_name": customer.last_name.clone(),
        })
    });
    json!({
        "store": {
            "id": store.id.as_str(),
            "name": store.name,
            "domain": host,
            "locale": store.locale,
            "currency": currency.as_str(),
            "timezone": store.timezone,
        },
        "theme": {
            "id": theme.manifest.id,
            "version": theme.manifest.version,
            "settings": theme.settings,
        },
        "cart": cart,
        "customer": customer,
        "mode": mode.as_str(),
    })
}

/// Resolves the customer for a session token, reusing a short-lived cache entry.
///
/// The cache key contains a SHA-256 digest of the token so raw credentials are
/// not retained. A logout or revocation may stay invisible for at most the
/// context cache TTL; explicit invalidation closes that window on the logout
/// path.
async fn resolve_context_customer(
    context: &AppContext,
    db: &StoreDatabase,
    store_id: &str,
    token: &str,
) -> Option<Arc<fastcart_module_customer::Customer>> {
    let key = format!("{store_id}:customer:{}", token_digest(token));
    if let Some(cached) = context.storefront_customer_cache.get(&key).await {
        return cached;
    }
    let customer = match CustomerService::new(db.clone())
        .session_customer(token)
        .await
    {
        Ok(customer) => customer.map(Arc::new),
        Err(error) => {
            tracing::warn!(error = %error, "could not resolve customer session context");
            None
        }
    };
    context
        .storefront_customer_cache
        .insert(key, customer.clone())
        .await;
    customer
}

/// Resolves the active cart for the request context.
///
/// An authenticated customer's newest open cart wins. Guests may present a
/// cart id cookie, but only for a guest cart; a customer-scoped cart must never
/// be exposed by guessing an identifier.
async fn resolve_context_cart(
    context: &AppContext,
    db: &StoreDatabase,
    store_id: &str,
    cookie: Option<&str>,
    customer: Option<&fastcart_module_customer::Customer>,
) -> serde_json::Value {
    let service = CartService::new(db.clone());
    let mut cart = None;
    if let Some(customer) = customer {
        let key = format!("{store_id}:customer-cart:{}", customer.id.as_str());
        cart = match context.storefront_cart_cache.get(&key).await {
            Some(cached) => cached,
            None => {
                let found = match service.active_cart_for_customer(&customer.id).await {
                    Ok(found) => found.map(Arc::new),
                    Err(error) => {
                        tracing::warn!(error = %error, "could not resolve customer cart context");
                        None
                    }
                };
                context
                    .storefront_cart_cache
                    .insert(key, found.clone())
                    .await;
                found
            }
        };
    }
    if cart.is_none()
        && let Some(id) = cookie
    {
        let key = format!("{store_id}:cart:{id}");
        let found = match context.storefront_cart_cache.get(&key).await {
            Some(cached) => cached,
            None => {
                let found = match service.get_cart(&CartId::from_string(id)).await {
                    Ok(found) => Some(Arc::new(found)),
                    Err(error) if error.is_not_found() => None,
                    Err(error) => {
                        tracing::warn!(error = %error, "could not resolve cart cookie context");
                        None
                    }
                };
                context
                    .storefront_cart_cache
                    .insert(key, found.clone())
                    .await;
                found
            }
        };
        if let Some(found) = found {
            let belongs = match (&found.customer_id, customer) {
                (None, _) => true,
                (Some(owner), Some(customer)) => owner == &customer.id,
                (Some(_), None) => false,
            };
            if belongs && found.status == fastcart_module_cart::CartStatus::Open {
                cart = Some(found);
            }
        }
    }
    cart.map_or(serde_json::Value::Null, |cart| {
        json!({
            "id": cart.id.as_str(),
            "currency": cart.currency_code.as_str(),
            "status": cart.status.as_str(),
            "item_count": cart.items.iter().map(|item| item.quantity).sum::<i64>(),
            "subtotal": cart.totals.subtotal,
            "total": cart.totals.total,
        })
    })
}

/// Hashes a session token for use in a cache key without retaining the token.
fn token_digest(token: &str) -> String {
    use sha2::{Digest, Sha256};
    Sha256::digest(token.as_bytes())
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

fn is_published_page(page: &Page) -> bool {
    page.status == PageStatus::Published && page.deleted_at.is_none()
}

pub(crate) fn runtime_response(response: RuntimeResponse, stream_timeout_ms: u64) -> Response {
    let status = StatusCode::from_u16(response.status).unwrap_or(StatusCode::BAD_GATEWAY);
    let mut builder = Response::builder().status(status);
    for (name, value) in response.headers {
        if is_hop_by_hop(&name) || name.eq_ignore_ascii_case(CONTENT_LENGTH.as_str()) {
            continue;
        }
        let Ok(name) = HeaderName::from_bytes(name.as_bytes()) else {
            continue;
        };
        let Ok(value) = HeaderValue::from_str(&value) else {
            continue;
        };
        builder = builder.header(name, value);
    }
    let body = match response.body {
        RuntimeBody::Full(bytes) => Body::from(bytes),
        RuntimeBody::Stream(stream) => {
            // Bound the whole body even when the runtime adapter does not.
            // A stalled sidecar connection must not pin an HTTP response
            // forever.
            let deadline = tokio::time::Instant::now()
                + std::time::Duration::from_millis(stream_timeout_ms.max(1));
            let limited = futures::stream::try_unfold(
                (stream, deadline),
                move |(mut stream, deadline)| async move {
                    let stream_budget = stream_timeout_ms;
                    let next = tokio::time::timeout_at(deadline, stream.next())
                        .await
                        .map_err(|_| RuntimeError::Timeout(stream_budget))?;
                    match next {
                        Some(item) => Ok::<_, RuntimeError>(Some((item?, (stream, deadline)))),
                        None => Ok(None),
                    }
                },
            );
            Body::from_stream(limited)
        }
    };
    builder.body(body).unwrap_or_else(|error| {
        runtime_error(
            StatusCode::INTERNAL_SERVER_ERROR,
            "RUNTIME_RESPONSE",
            &format!("invalid storefront response: {error}"),
            "",
        )
    })
}

pub(crate) fn runtime_error(
    status: StatusCode,
    code: &'static str,
    message: &str,
    request_id: &str,
) -> Response {
    let request_id = (!request_id.is_empty()).then(|| request_id.to_owned());
    (
        status,
        Json(json!({
            "error": {
                "code": code,
                "message": message,
                "request_id": request_id,
            }
        })),
    )
        .into_response()
}

fn is_reserved_path(path: &str) -> bool {
    path == "/metrics"
        || path.starts_with("/api/")
        || path == "/api"
        || path.starts_with("/internal/")
        || path.starts_with("/health")
}

pub(crate) fn is_hop_by_hop(name: &str) -> bool {
    [
        CONNECTION.as_str(),
        "keep-alive",
        TE.as_str(),
        TRAILER.as_str(),
        TRANSFER_ENCODING.as_str(),
        UPGRADE.as_str(),
        "proxy-authenticate",
        "proxy-authorization",
        "proxy-connection",
    ]
    .iter()
    .any(|candidate| name.eq_ignore_ascii_case(candidate))
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use base64::Engine;
    use base64::engine::general_purpose::URL_SAFE_NO_PAD;
    use fastcart_kernel::{StoreId, ThemeId};

    use super::{capability_token, is_reserved_path, match_theme_route, redirect_location};

    #[test]
    fn capability_tokens_are_signed_when_a_secret_is_configured() {
        let store_id = StoreId::from_string("store_1");
        let theme_id = ThemeId::new();
        let token = capability_token(Some("capability-secret"), &store_id, &theme_id, "chat");
        let (payload, signature) = token.split_once('.').expect("signed token");
        assert!(!signature.is_empty());
        let payload: serde_json::Value =
            serde_json::from_slice(&URL_SAFE_NO_PAD.decode(payload).unwrap()).unwrap();
        assert_eq!(payload["store"], "store_1");
        assert_eq!(payload["theme"], theme_id.as_str());
        assert_eq!(payload["capability"], "chat");
        assert!(payload["exp"].as_i64().unwrap() > 0);

        let opaque = capability_token(None, &store_id, &theme_id, "chat");
        assert!(!opaque.contains('.'));
    }

    #[test]
    fn theme_routes_capture_only_safe_handles() {
        let routes = BTreeMap::from([
            ("product".to_owned(), "/products/{handle}".to_owned()),
            ("collection".to_owned(), "/collections/{handle}".to_owned()),
        ]);
        let product = match_theme_route(&routes, "/products/hoodie").expect("product route");
        assert_eq!(product.kind, "product");
        assert_eq!(product.handle, "hoodie");

        assert!(match_theme_route(&routes, "/products/hoodie/extra").is_none());
        assert!(match_theme_route(&routes, "/products/").is_none());
        assert!(match_theme_route(&routes, "/collections/Hoodie!").is_none());
        assert!(match_theme_route(&routes, "/other").is_none());
    }

    #[test]
    fn redirects_only_accept_site_relative_targets() {
        assert_eq!(
            redirect_location("/products/hoodie")
                .and_then(|value| value.to_str().ok().map(str::to_owned)),
            Some("/products/hoodie".to_owned())
        );
        for unsafe_target in [
            "https://evil.example",
            "//evil.example",
            "/\\evil.example",
            "/line\nbreak",
            "relative",
            "",
        ] {
            assert!(
                redirect_location(unsafe_target).is_none(),
                "{unsafe_target:?}"
            );
        }
    }

    #[test]
    fn api_and_health_paths_are_reserved() {
        assert!(is_reserved_path("/api/v1/store/products"));
        assert!(is_reserved_path("/api"));
        assert!(is_reserved_path("/internal/storefront/products"));
        assert!(is_reserved_path("/health/ready"));
        assert!(is_reserved_path("/metrics"));
        assert!(!is_reserved_path("/"));
        assert!(!is_reserved_path("/products/hoodie"));
        assert!(!is_reserved_path("/robots.txt"));
    }
}
